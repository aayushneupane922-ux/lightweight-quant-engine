"""Regenerates THIRD_PARTY_NOTICES.md from the same scan `license_gate.py`
uses (docs/11 §11.11) — one step covers every runtime dependency's notice,
`certifi`'s MPL-2.0 included. Run after any runtime/`ui`-extra dependency
change: `python scripts/generate_third_party_notices.py`.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from license_gate import _normalize, _pip_licenses_json, runtime_closure  # noqa: E402

OUTPUT_PATH = Path(__file__).resolve().parent.parent / "THIRD_PARTY_NOTICES.md"


def main() -> int:
    closure, missing_roots = runtime_closure()
    if missing_roots:
        print(f"generate_third_party_notices: FAIL — missing roots: {sorted(missing_roots)}")
        return 1

    packages = _pip_licenses_json()
    by_name = {_normalize(pkg["Name"]): pkg for pkg in packages}

    lines = [
        "# Third-Party Notices",
        "",
        "Auto-generated by `scripts/generate_third_party_notices.py` from the same",
        "scan `scripts/license_gate.py` runs (full runtime dependency closure — base",
        "`[project.dependencies]` plus the `ui` extra, promoted into the running",
        "product as of M7). Do not hand-edit; regenerate instead.",
        "",
    ]
    for name in sorted(closure):
        pkg = by_name.get(name)
        if pkg is None:
            continue
        lines.append(f"## {pkg['Name']} {pkg.get('Version', '')}".rstrip())
        lines.append(f"- License: {pkg.get('License', 'UNKNOWN')}")
        url = pkg.get("URL")
        if url and url != "UNKNOWN":
            lines.append(f"- URL: {url}")
        lines.append("")

    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"generate_third_party_notices: wrote {OUTPUT_PATH} ({len(closure)} packages).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
